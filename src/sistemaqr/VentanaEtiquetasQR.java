    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        javax.swing.JFileChooser selector
                = new javax.swing.JFileChooser();

        if (selector.showSaveDialog(this)
                == javax.swing.JFileChooser.APPROVE_OPTION) {

            try {
                java.io.File archivo = selector.getSelectedFile();

                if (!archivo.getName().toLowerCase().endsWith(".png")) {
                    archivo = new java.io.File(
                            archivo.getAbsolutePath() + ".png");
                }

                controlador.guardarEtiqueta(archivo);

                javax.swing.JOptionPane.showMessageDialog(
                        this, "Etiqueta guardada correctamente");

            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, e.getMessage());
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

